let check_svd name input ~full_matrices tol () =
  need_gpu ();
  Backend.with_platform "gpu" (fun () ->
      let _, before = Backend.stats () in
      let outs =
        Api.jit_flat
          (function
            | [ a ] -> Li.svd ~full_matrices ~compute_uv:true a
            | _ -> Alcotest.fail "arity")
          [ input ]
      in
      let _, after = Backend.stats () in
      Alcotest.(check int)
        "no host fallback" (List.length before) (List.length after);
      match outs with
      | [ u; s; vh ] ->
          compare_outputs name (List.assoc name expected_gpu) [ s ];
          let nd_u = host u and nd_a = host input in
          let a = as_complex nd_a and uu = as_complex nd_u in
          let vv = as_complex (host vh) and ss = as_complex (host s) in
          let m = (Ndarray.shape nd_a).(0) and n = (Ndarray.shape nd_a).(1) in
          let ucols = (Ndarray.shape nd_u).(1) in
          let k = Array.length ss in
          for row = 0 to m - 1 do
            for col = 0 to n - 1 do
              let sum = ref Complex.zero in
              for i = 0 to k - 1 do
                sum :=
                  Complex.add !sum
                    (Complex.mul
                       (Complex.mul uu.((row * ucols) + i) ss.(i))
                       vv.((i * n) + col))
              done;
              if Complex.norm (Complex.sub !sum a.((row * n) + col)) > tol then
                Alcotest.failf "svd reconstruction at %d,%d off by %g" row col
                  (Complex.norm (Complex.sub !sum a.((row * n) + col)))
            done
          done;
          for x = 0 to ucols - 1 do
            for y = 0 to ucols - 1 do
              let sum = ref Complex.zero in
              for row = 0 to m - 1 do
                sum :=
                  Complex.add !sum
                    (Complex.mul
                       (Complex.conj uu.((row * ucols) + x))
                       uu.((row * ucols) + y))
              done;
              let want =
                { Complex.re = (if x = y then 1.0 else 0.0); im = 0.0 }
              in
              if Complex.norm (Complex.sub !sum want) > tol then
                Alcotest.failf "u is not unitary at %d,%d" x y
            done
          done
      | _ -> Alcotest.fail "arity")

let only_cpu_table name =
  not
    (List.mem name
       [
         "gpu_tridiagonal";
         "gpu_tridiagonal_batch";
         "lu_f32";
         "lu_f64_tall";
         "lu_f64_wide";
         "lu_c64";
         "lu_batch";
         "solve_f64";
         "det_f64";
         "inv_f32";
         "slogdet_c";
       ])

let () =
  let all_cases = native_cases @ gpu_cases in
  Alcotest.run "backend_native"
    [
      ( "platform",
        [
          Alcotest.test_case "selected" `Quick selected_platform;
          Alcotest.test_case "unknown" `Quick unknown_platform;
          Alcotest.test_case "cpu devices" `Quick cpu_devices_always;
          Alcotest.test_case "unconfigured gpu" `Quick unconfigured_gpu_raises;
          Alcotest.test_case "wrong plugin" `Quick rejects_wrong_gpu_plugin;
          Alcotest.test_case "platform_index" `Quick platform_index_under_jit;
        ] );
      ( "native on cpu",
        List.map (cpu_case expected_cpu)
          (List.filter (fun (n, _, _) -> only_cpu_table n) all_cases) );
      ( "lapack stays on cpu",
        [
          Alcotest.test_case "lu" `Quick
            (cpu_fallback_stays "lu_f32" lu [ f32 [| 3; 3 |] m3 ]);
          Alcotest.test_case "svd" `Quick
            (cpu_fallback_stays "svd_vals_f64"
               (one (fun a -> List.hd (Li.svd ~compute_uv:false a)))
               [ f64 [| 4; 3 |] m43 ]);
          Alcotest.test_case "eigh" `Quick
            (cpu_fallback_stays "gpu_eigvals" eigvals_only [ eig_real ]);
          Alcotest.test_case "tridiagonal" `Quick
            (let name, f, args =
               List.find (fun (n, _, _) -> n = "gpu_tridiagonal") gpu_cases
             in
             cpu_fallback_stays name f args);
        ] );
      ( "native on gpu",
        List.map (gpu_case expected_gpu) (all_cases @ gpu_only_cases) );
      ( "gpu runtime",
        [
          Alcotest.test_case "eigh real" `Slow
            (eigh_gpu "gpu_eigvals" eig_real 1e-13);
          Alcotest.test_case "eigh complex" `Slow
            (eigh_gpu "gpu_eigvals_c" eig_complex 1e-5);
          Alcotest.test_case "svd full tall" `Slow
            (check_svd "svd_vals_uv"
               (f64 [| 4; 3 |] m43)
               ~full_matrices:true 1e-12);
          Alcotest.test_case "svd reduced tall" `Slow
            (check_svd "svd_tall_reduced_vals"
               (f64 [| 4; 3 |] m43)
               ~full_matrices:false 1e-12);
          Alcotest.test_case "svd full wide" `Slow
            (check_svd "svd_wide_full_vals"
               (f64 [| 3; 4 |] m34)
               ~full_matrices:true 1e-12);
          Alcotest.test_case "svd complex" `Slow
            (check_svd "svd_c_vals"
               (c64 [| 3; 3 |] c3)
               ~full_matrices:true 5e-5);
          Alcotest.test_case "eigh degenerate" `Slow eigh_degenerate;
          Alcotest.test_case "c64 matmul" `Slow c64_matmul;
          Alcotest.test_case "resident" `Slow resident_on_gpu;
          Alcotest.test_case "moves" `Slow moves_between_platforms;
        ] );
    ]
