  if D.gpu_configured () && not gpu_ready then Alcotest.skip ();
  if gpu_ready then (
    Alcotest.(check string) "platform" "cuda" (Backend.current_platform ());
    Alcotest.(check string) "default backend" "gpu" (Api.default_backend ());
    Alcotest.(check (list string)) "devices" [ "cuda:0" ] (Api.devices ());
    Alcotest.(check int) "device count" 1 (Api.device_count ());
    Alcotest.(check bool)
      "device kind" true
