let f32 shape xs = Concrete (Ndarray.of_floats Dtype.F32 shape xs)
let f64 shape xs = Concrete (Ndarray.of_floats Dtype.F64 shape xs)
let i32 shape xs = Concrete (Ndarray.of_floats Dtype.I32 shape xs)
let u8 shape xs = Concrete (Ndarray.of_floats Dtype.Uint8 shape xs)

let complex_of xs =
  Array.init
    (Array.length xs / 2)
    (fun i -> { Complex.re = xs.(2 * i); im = xs.((2 * i) + 1) })

let c64 shape xs =
  Concrete (Ndarray.of_complex Dtype.Complex64 shape (complex_of xs))

let c128 shape xs =
  Concrete (Ndarray.of_complex Dtype.Complex128 shape (complex_of xs))

let host = function
  | Concrete nd -> nd
  | Device b -> Pjrt.Buffer.to_host b
  | Tracer _ -> Alcotest.fail "expected a concrete result"

let unravel shape flat =
  let r = Array.length shape in
  let idx = Array.make r 0 in
  let rem = ref flat in
  for i = r - 1 downto 0 do
    idx.(i) <- !rem mod shape.(i);
    rem := !rem / shape.(i)
  done;
  idx

let flatten nd =
  let shape = Ndarray.shape nd in
  let n = Array.fold_left ( * ) 1 shape in
  match Ndarray.dtype nd with
  | Dtype.Complex64 | Dtype.Complex128 ->
      Array.concat
        (List.init n (fun i ->
             let c = Ndarray.get_c nd (unravel shape i) in
             [| c.Complex.re; c.Complex.im |]))
  | _ -> Array.init n (fun i -> Ndarray.get_f nd (unravel shape i))

let tolerance nd =
  match Ndarray.dtype nd with
  | Dtype.F64 | Dtype.Complex128 -> 1e-10
  | _ -> 2e-4

let close tol want got =
  (Float.is_nan want && Float.is_nan got)
  || want = got
  || Float.abs (want -. got) <= tol *. Float.max 1.0 (Float.abs want)

let compare_outputs name expected outs =
  Alcotest.(check int)
    (name ^ " outputs") (List.length expected) (List.length outs);
  List.iteri
    (fun i ((shape, want), out) ->
      let nd = host out in
      let label = Printf.sprintf "%s[%d]" name i in
      Alcotest.(check (array int)) (label ^ " shape") shape (Ndarray.shape nd);
      let got = flatten nd in
      Alcotest.(check int)
        (label ^ " size") (Array.length want) (Array.length got);
      Array.iteri
        (fun j w ->
          if not (close (tolerance nd) w got.(j)) then
            Alcotest.failf "%s element %d: expected %.17g, got %.17g" label j w
              got.(j))
        want)
    (List.combine expected outs)

let run_native table name f args =
  let compiled, fallbacks = Backend.stats () in
  let outs = Api.jit_flat f args in
  let compiled', fallbacks' = Backend.stats () in
  (match List.filteri (fun i _ -> i >= List.length fallbacks) fallbacks' with
  | [] -> ()
  | reason :: _ -> Alcotest.failf "%s fell back to the host: %s" name reason);
  Alcotest.(check int) (name ^ " compiled once") (compiled + 1) compiled';
  compare_outputs name (List.assoc name table) outs

