    Alcotest.(check bool)
      "platform version" true
      (String.starts_with ~prefix:"cuda " (Backend.platform_version ())))
  else (
    Alcotest.(check string) "platform" "cpu" (Backend.current_platform ());
    Alcotest.(check string) "default backend" "cpu" (Api.default_backend ());
    Alcotest.(check (list string)) "devices" [ "cpu:0" ] (Api.devices ()))

