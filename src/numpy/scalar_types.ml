module C = Core
module T = Types
module D = Dtype

let get_aval = C.get_aval
let dtype v = (get_aval v).T.dtype
let bind1 = C.bind1

let convert v dt =
  if dtype v = dt then v else bind1 (T.Convert_element_type dt) [ v ]

let by_dtype dt v = convert v (Dtypes.canonicalize_dtype dt)
let bool_ v = convert v D.Bool
let int32 v = convert v D.I32
let int64 = by_dtype D.I64
let float32 v = convert v D.F32
let float64 = by_dtype D.F64
let single = float32
let double = float64
let int_ = int64
let float_ = float64
let bfloat16 = by_dtype D.Bf16
let float16 = by_dtype D.F16
let int8 = by_dtype D.I8
let int16 = by_dtype D.I16
let uint8 = by_dtype D.Uint8
let uint16 = by_dtype D.Uint16
let uint32 = by_dtype D.Uint32
let uint64 = by_dtype D.Uint64
let uint = by_dtype D.Uint64
let complex64 = by_dtype D.Complex64
let complex128 = by_dtype D.Complex128
let csingle = complex64
let cdouble = complex128
