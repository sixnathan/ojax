let platform_index_value () =
  host (Lax.platform_index ~platforms:branches) |> flatten |> fun v -> v.(0)

let platform_index_under_jit () =
  let jitted =
    Api.jit_flat (fun _ -> [ Lax.platform_index ~platforms:branches ])
  in
  let check_on platform want =
    Backend.with_platform platform (fun () ->
        Alcotest.(check (float 0.0))
          (platform ^ " eager") want (platform_index_value ());
        let compiled =
          host (List.hd (jitted [ f32 [||] [| 0. |] ])) |> flatten
        in
        Alcotest.(check (float 0.0)) (platform ^ " jit") want compiled.(0);
        Alcotest.(check string)
          (platform ^ " platform_dependent")
          platform
          (L.platform_dependent
             ~default:(fun () -> "default")
             ~cuda:(fun () -> "cuda")
             ~cpu:(fun () -> "cpu")
             ()))
  in
  check_on "cpu" 0.0;
  if gpu_ready then check_on "cuda" 1.0

