let as_complex nd =
  let shape = Ndarray.shape nd in
  let n = Array.fold_left ( * ) 1 shape in
  Array.init n (fun i ->
      let idx = unravel shape i in
      match Ndarray.dtype nd with
      | Dtype.Complex64 | Dtype.Complex128 -> Ndarray.get_c nd idx
      | _ -> { Complex.re = Ndarray.get_f nd idx; im = 0.0 })

let check_eigenpairs tol input v w =
  let a = as_complex input
  and vectors = as_complex v
  and values = as_complex w in
  let n = Array.length values in
  for col = 0 to n - 1 do
    for row = 0 to n - 1 do
      let lhs = ref Complex.zero in
      for k = 0 to n - 1 do
        lhs :=
          Complex.add !lhs
            (Complex.mul a.((row * n) + k) vectors.((k * n) + col))
      done;
      let rhs = Complex.mul values.(col) vectors.((row * n) + col) in
      if Complex.norm (Complex.sub !lhs rhs) > tol then
        Alcotest.failf "eigenpair residual too large at %d,%d: %g" row col
          (Complex.norm (Complex.sub !lhs rhs))
    done
  done

